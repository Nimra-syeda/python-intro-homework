print(not True and False) # not True is False, False and False is False. 
print(True or False and  False) # First we evalute 'and'operator in this condition- false and false is False and True or False is "True",or operator is evaluated last, when there is two or more operators in a boolean expression.
print(not (5 > 3)) # not(5>3)is not True is False.
print(10 == 10 and 4 != 4) # 10 == 10is True and 4 != 4 is False, True and False is False. When there is 'and'operator both values must be True.
print(not False or not True) # not False is True and not True is False, True or False is True.
